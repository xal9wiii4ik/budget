"""Transaction CRUD + monthly summary over the ``transactions`` table.

Two structural authorization pillars (architecture §3), carried from categories.py:

* **Reads** filter ``user_id = me`` (transactions are never system rows). The
  *category reference* a transaction points at is still visible-scoped on write.
* **Writes** force ``user_id = me`` and never read ``user_id`` from the body.

No-oracle: the transaction's own path id uses ``404 TRANSACTION_NOT_FOUND`` for
cross-user and missing alike (``_load_own`` filters ``user_id = me``, one code
path). A *body* ``category_id`` that is foreign/missing is ``422
CATEGORY_NOT_FOUND`` (``load_visible_category`` returns ``None`` for both, one
code path); an archived visible target is ``422 CATEGORY_ARCHIVED``. The addressed
resource (the transaction) is fine, so the body — not the resource — is the 422.

Summary SQL lives here (decision k / grooming precedent): aggregate SQL sits with
its router at the first consumer; 4.1 (statistics) extracts. ``_get_or_create_profile``
likewise stays inline as the first profile-reading consumer; the second extracts.
"""

import uuid
from datetime import date

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy import case, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from budget_api.auth import current_active_user
from budget_api.category_access import load_visible_category
from budget_api.db import get_session
from budget_api.enums import TransactionKind
from budget_api.models import Profile, Transaction, User
from budget_api.models.profile import DEFAULT_BASE_CURRENCY
from budget_api.schemas.transaction import (
    CategorySummary,
    SummaryRead,
    TransactionCreate,
    TransactionError,
    TransactionList,
    TransactionRead,
    TransactionUpdate,
)

router = APIRouter()

_MONTH_PATTERN = r"^\d{4}-(0[1-9]|1[0-2])$"

# Mirrors routers/categories.py: every HTTPException.detail below is a stable
# UPPER_SNAKE code carried in {"detail": ...} (the TransactionError shape).
_NOT_FOUND: dict[int | str, dict[str, object]] = {
    status.HTTP_404_NOT_FOUND: {"model": TransactionError}
}
# AM-5: POST/PATCH 422 emits BOTH arms at runtime — our business codes
# ({"detail": CODE}, TransactionError) and FastAPI's Pydantic array
# (HTTPValidationError). Declaring only {"model": TransactionError} would suppress
# the auto HTTPValidationError and make the generated type lie about one arm, so we
# declare the honest union as a raw content schema. HTTPValidationError is NOT
# hand-declared (that would mangle the component name); it already exists in the
# schema (generated by parameterized routes) and the GET routes keep emitting it.
_UNPROCESSABLE: dict[int | str, dict[str, object]] = {
    status.HTTP_422_UNPROCESSABLE_CONTENT: {
        "description": "Business rule rejection (string code) or validation error",
        "content": {
            "application/json": {
                "schema": {
                    "anyOf": [
                        {"$ref": "#/components/schemas/TransactionError"},
                        {"$ref": "#/components/schemas/HTTPValidationError"},
                    ]
                }
            }
        },
    }
}


def _serialize(tx: Transaction) -> TransactionRead:
    return TransactionRead(
        id=tx.id,
        amount_minor=tx.amount_minor,
        kind=TransactionKind(tx.kind),
        currency=tx.currency,
        category_id=tx.category_id,
        occurred_at=tx.occurred_at,
        note=tx.note,
        created_at=tx.created_at,
    )


async def _get_or_create_profile(session: AsyncSession, user_id: uuid.UUID) -> Profile:
    """Self-healing profile read (1.2 §6): a pre-1.2 user may lack a profiles row.

    Called on POST only, where a commit happens anyway, so a self-healed row
    persists atomically with the transaction. The summary GET does NOT create a
    profile (a GET stays read-only) — it falls back to DEFAULT_BASE_CURRENCY.
    """
    profile = await session.get(Profile, user_id)
    if profile is None:
        profile = Profile(user_id=user_id, base_currency=DEFAULT_BASE_CURRENCY)
        session.add(profile)
        await session.flush()  # persist within the same tx; commit rides the create
    return profile


async def _validate_category(
    session: AsyncSession, category_id: uuid.UUID, user_id: uuid.UUID
) -> None:
    """Body category-ref policy (decision e). Call only when category_id is non-null.

    load_visible → None ⇒ 422 CATEGORY_NOT_FOUND (foreign == missing, one code path,
    byte-identical); a visible-but-archived target ⇒ 422 CATEGORY_ARCHIVED. Order
    preserves the existence oracle: a foreign archived category is CATEGORY_NOT_FOUND,
    never CATEGORY_ARCHIVED.
    """
    cat = await load_visible_category(session, category_id, user_id)
    if cat is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail="CATEGORY_NOT_FOUND",
        )
    if cat.archived:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail="CATEGORY_ARCHIVED",
        )


async def _load_own(
    session: AsyncSession, transaction_id: uuid.UUID, user_id: uuid.UUID
) -> Transaction | None:
    """user_id-scoped load; foreign/missing → None → 404 (no-oracle, one code path)."""
    return await session.scalar(
        select(Transaction).where(
            Transaction.id == transaction_id, Transaction.user_id == user_id
        )
    )


@router.post(
    "",
    response_model=TransactionRead,
    status_code=status.HTTP_201_CREATED,
    responses=_UNPROCESSABLE,
)
async def create_transaction(
    payload: TransactionCreate,
    user: User = Depends(current_active_user),
    session: AsyncSession = Depends(get_session),
) -> TransactionRead:
    if payload.category_id is not None:
        await _validate_category(session, payload.category_id, user.id)
    profile = await _get_or_create_profile(session, user.id)
    tx = Transaction(
        user_id=user.id,
        amount_minor=payload.amount_minor,
        kind=payload.kind.value,
        currency=profile.base_currency,
        category_id=payload.category_id,
        occurred_at=payload.occurred_at,
        note=payload.note,
    )
    session.add(tx)
    await session.commit()
    await session.refresh(tx)
    return _serialize(tx)


@router.get("", response_model=TransactionList)
async def list_transactions(
    from_: date | None = Query(default=None, alias="from"),
    to: date | None = Query(default=None, alias="to"),
    category_id: uuid.UUID | None = None,
    kind: TransactionKind | None = None,
    limit: int = Query(default=50, ge=1, le=200),
    offset: int = Query(default=0, ge=0),
    user: User = Depends(current_active_user),
    session: AsyncSession = Depends(get_session),
) -> TransactionList:
    # Read filters never error (decision l): a foreign category_id / from>to simply
    # matches nothing. No existence check, no oracle.
    filters = [Transaction.user_id == user.id]
    if from_ is not None:
        filters.append(Transaction.occurred_at >= from_)
    if to is not None:
        filters.append(Transaction.occurred_at <= to)
    if category_id is not None:
        filters.append(Transaction.category_id == category_id)
    if kind is not None:
        filters.append(Transaction.kind == kind.value)

    total = await session.scalar(
        select(func.count()).select_from(Transaction).where(*filters)
    )
    rows = (
        await session.scalars(
            select(Transaction)
            .where(*filters)
            .order_by(
                Transaction.occurred_at.desc(),
                Transaction.created_at.desc(),
                Transaction.id,
            )
            .limit(limit)
            .offset(offset)
        )
    ).all()
    return TransactionList(items=[_serialize(t) for t in rows], total=total or 0)


@router.get("/summary", response_model=SummaryRead)  # BEFORE any /{id} (Risks)
async def summary(
    month: str = Query(pattern=_MONTH_PATTERN),
    user: User = Depends(current_active_user),
    session: AsyncSession = Depends(get_session),
) -> SummaryRead:
    # AM-6: the Query pattern is the ONLY month validator — a malformed month is a
    # Pydantic 422 before we get here, so date() below can never receive month 0/13.
    year, mon = int(month[:4]), int(month[5:7])
    month_start = date(year, mon, 1)
    next_month_start = date(year + (mon == 12), (mon % 12) + 1, 1)
    period = (
        Transaction.user_id == user.id,
        Transaction.occurred_at >= month_start,
        Transaction.occurred_at < next_month_start,
    )

    # Totals — CASE aggregate over kind (arch §1 verdict, binding).
    income_sum = func.coalesce(
        func.sum(
            case(
                (
                    Transaction.kind == TransactionKind.income.value,
                    Transaction.amount_minor,
                ),
                else_=0,
            )
        ),
        0,
    )
    expense_sum = func.coalesce(
        func.sum(
            case(
                (
                    Transaction.kind == TransactionKind.expense.value,
                    Transaction.amount_minor,
                ),
                else_=0,
            )
        ),
        0,
    )
    income_minor, expense_minor = (
        await session.execute(select(income_sum, expense_sum).where(*period))
    ).one()
    net_minor = income_minor - expense_minor  # signed: income - expense

    # Breakdown — GROUP BY feeding by_category (NULL category_id = uncategorized).
    total_col = func.sum(Transaction.amount_minor)
    rows = (
        await session.execute(
            select(Transaction.category_id, Transaction.kind, total_col.label("total"))
            .where(*period)
            .group_by(Transaction.category_id, Transaction.kind)
            .order_by(Transaction.kind, total_col.desc())
        )
    ).all()
    by_category = [
        CategorySummary(category_id=cid, kind=TransactionKind(k), total_minor=total)
        for cid, k, total in rows
    ]

    # Read-only base-currency fallback: no profile write on a GET (POST self-heals).
    profile = await session.get(Profile, user.id)
    currency = profile.base_currency if profile is not None else DEFAULT_BASE_CURRENCY

    return SummaryRead(
        month=month,
        currency=currency,
        income_minor=income_minor,
        expense_minor=expense_minor,
        net_minor=net_minor,
        by_category=by_category,
    )


@router.patch(
    "/{transaction_id}",
    response_model=TransactionRead,
    responses={**_NOT_FOUND, **_UNPROCESSABLE},
)
async def update_transaction(
    transaction_id: uuid.UUID,
    payload: TransactionUpdate,
    user: User = Depends(current_active_user),
    session: AsyncSession = Depends(get_session),
) -> TransactionRead:
    tx = await _load_own(session, transaction_id, user.id)
    if tx is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="TRANSACTION_NOT_FOUND"
        )

    fields = payload.model_fields_set
    # NOT NULL columns: an explicit null cannot clear them (else a bare apply 500s
    # on IntegrityError) — reject with a custom *_REQUIRED 422.
    if "amount_minor" in fields and payload.amount_minor is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail="AMOUNT_REQUIRED"
        )
    if "kind" in fields and payload.kind is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail="KIND_REQUIRED"
        )
    if "occurred_at" in fields and payload.occurred_at is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail="OCCURRED_AT_REQUIRED",
        )

    # Category validated ONLY when in the field set AND non-null (decision e): an
    # amount-only edit of a tx whose category was archived after the fact must still
    # succeed; an explicit null clears to uncategorized with no validation.
    if "category_id" in fields and payload.category_id is not None:
        await _validate_category(session, payload.category_id, user.id)

    if "amount_minor" in fields:
        assert payload.amount_minor is not None  # 422-guarded above
        tx.amount_minor = payload.amount_minor
    if "kind" in fields:
        assert payload.kind is not None  # 422-guarded above
        tx.kind = payload.kind.value
    if "occurred_at" in fields:
        assert payload.occurred_at is not None  # 422-guarded above
        tx.occurred_at = payload.occurred_at
    if "category_id" in fields:
        tx.category_id = payload.category_id  # explicit null clears
    if "note" in fields:
        tx.note = payload.note  # null/"" clears (validator normalized "" → None)

    await session.commit()
    await session.refresh(tx)
    return _serialize(tx)


@router.delete(
    "/{transaction_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    response_model=None,
    responses=_NOT_FOUND,
)
async def delete_transaction(
    transaction_id: uuid.UUID,
    user: User = Depends(current_active_user),
    session: AsyncSession = Depends(get_session),
) -> None:
    # Real DELETE (decision a): transactions are leaf rows, nothing references them.
    tx = await _load_own(session, transaction_id, user.id)
    if tx is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="TRANSACTION_NOT_FOUND"
        )
    await session.delete(tx)
    await session.commit()
