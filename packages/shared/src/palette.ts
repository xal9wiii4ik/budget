// The ONE place a colour value is written for web AND mobile. Web renders these
// into `--l-*` / `--d-*` custom properties through `paletteCss.ts`; mobile builds
// its `{ light, dark }` theme objects from the same two records. Dark is NOT an
// inversion: it has its own surfaces and states its borders by alpha.
// Nothing else in either client may contain a colour literal.
// Pure data — no imports, no logic; values are hex or `rgba()` strings (RN takes both).

