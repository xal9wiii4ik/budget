// The picker's option list, in code order (the SELECT sorts by the localized
// label, which only the UI knows). Derived from the table so the two can never
// drift apart.
export const COUNTRY_CODES: readonly string[] = Object.keys(COUNTRY_CURRENCIES);

// Shape check for a country code, mirroring the server CHECK (`^[A-Z]{2}$`).
export const COUNTRY_CODE_PATTERN = /^[A-Z]{2}$/;

/**
 * The currency spent in `country`, or `null` when there is nothing to say —
 * no country chosen, a code this table does not know, or a malformed one.
 *
 * `null` is a real answer, not a failure: the caller (the spend-currency default)
 * falls back to the selected account's currency, which is always known. Guessing
 * a currency for an unknown country is exactly the kind of invented money fact
 * this codebase refuses to produce.
 */
export function countryToCurrency(country: string | null | undefined): string | null {
  if (!country) return null;
  return COUNTRY_CURRENCIES[country] ?? null;
}
